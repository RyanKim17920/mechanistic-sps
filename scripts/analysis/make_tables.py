def write_roster_full(out: Path):
    """One row per SEED RUN of every 20B arm; a run outside the seed-rule mean is starred."""
    L = D.ledger()
    rel = train_rel_same_kernel()
    assert head_tying_speed_effect() < 0.01
    keys = [k for k in ARMS if any(s in L for s in ARMS[k]["seeds"])]
    runs_by_key = {k: [s for s in ARMS[k]["seeds"] if s in L] for k in keys}
    mean_set = {k: set(D.mean_runs(k)) for k in keys}
    extra_notes = [tex(paper_name(k)) + ", " + ARMS[k].get("extra_note", {}).get(run, "an extra seed")
                   for k in keys for run in runs_by_key[k] if run not in mean_set[k]]
    extra = (r" $^*$: a run beyond the two the main text's seed rule means over (" +
             "; ".join(extra_notes) + ").") if extra_notes else ""
    cap = (r"Models trained on 20B tokens, one row per seed run. Variant: LM head / "
           r"prediction input; Shared: weights reused across the streams; Read: the state "
           r"level prediction layer $\ell$ reads ($\ell{-}1$: the state entering layer $\ell$). "
           r"Parameters are total and non-embedding; Speed is training throughput relative to "
           r"the tied-head Transformer on the same "
           r"attention kernel, from the benchmark of Tab.~\ref{tab:efficiency}, which prints a subset "
           r"of these models (--: not measured); NLL is "
           r"validation nats/token." + extra)
    header = [r"Model & Variant & Shared & Read & \multicolumn{2}{c}{Params (M)} & GFLOPs & "
              r"Speed & NLL \\",
              r"\cmidrule(lr){5-6}",
              r" & & & & total & non-emb. & /token & & (nats/token) \\"]

    def row(k):
        f, st, runs = config_facts(k), D.arch_stats(k), runs_by_key[k]
        n = len(runs)
        # Read shows the bare level; the caption glosses l-1 once
        arch = [tex(variant(k, qualifiers=False)), f["shared"], f["read_disp"],
                f"{st['params_total'] / 1e6:.1f}", f"{st['params_nonemb'] / 1e6:.1f}",
                f"{st['flops_fwd_per_token'] / 1e9:.3f}",
                f"{rel[k]:.2f}" if k in rel else "--"]
        lines = []
        for i, run in enumerate(runs):
            name = tex(roster_name(k)) + (f" (s{i + 1})" if n > 1 else "")
            nll = fmt(L[run], 3) + ("" if run in mean_set[k] else r"$^{*}$")
            if n > 1:
                # "=": wrap at the width of the p-columns (Variant, Shared)
                cells = [name] + ([rf"\multirow{{{n}}}{{{'=' if j < 2 else '*'}}}{{{c}}}"
                                   for j, c in enumerate(arch)] if i == 0
                                  else [""] * len(arch)) + [nll]
            else:
                cells = [name] + arch + [nll]
            lines.append(" & ".join(cells) + r" \\")
        return lines
    spec = (r">{\raggedright\arraybackslash}p{3.9cm}>{\raggedright\arraybackslash}p{2.0cm}"
            r">{\raggedright\arraybackslash}p{1.9cm}lrrrrl")
    write_float(out, "tab_roster_full", table_env(
        "tab:roster_full", cap, spec, header, grouped_body(grouped(keys), row), "2pt",
        size=r"\scriptsize"))


def write_efficiency(out: Path):
    W = wallclock_by_arm()
    rows = []
    for tag in WC["rows"]:
        rs = W.get(tag, [])
        exp = WC["arms"][tag]
        train, n = _median_metric(rs, "train")
        if train is None:
            print(f"[efficiency] no successful {WC['tag']} train rep for {tag}; skipped")
            continue
        kv = next((_num(r.get("kv_bytes_per_token")) for r in rs
                   if _num(r.get("kv_bytes_per_token")) is not None), None)
        decode = next((r["decode"].get("status") for r in rs if isinstance(r.get("decode"), dict)),
                      None)
        # same-kernel reference: the two-tower family runs on flex-attention, the rest on the
