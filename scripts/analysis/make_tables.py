WEIGHTS = {"standard": "--", "sps": "shared", "none": "separate", "attn+MLP": "shared"}
PRED_INPUT_WORDS = {"--": "--", "pause": PREDTOK + " token", "table": "own embedding"}
# SPS's read, "level l-1", glossed: prediction layer l attends to the state as it ENTERS
# state layer l
READ_GLOSS = {r"$\ell{-}1$": r"$\ell{-}1$ (input to layer $\ell$)"}


def write_model_definitions(out: Path):
    """One row per model family, grouped (main models / controls); every arm a row names
    must agree on every column."""
    body = []
    for gi, (group, rows) in enumerate(MANIFEST["model_definitions"]):
        if gi:
            body.append(r"\midrule")
        body.append(r"\multicolumn{6}{@{}l}{\emph{" + group + r"}} \\")
        for name, keys in rows:
            cells = set()
            for k in keys:
                f = config_facts(k)
                cells.add((WEIGHTS[f["family"] if f["family"] != "two_tower" else f["tying"]],
                           READ_GLOSS.get(f["read_disp"], f["read_disp"]),
                           PRED_INPUT_WORDS[f["pred_input"]], f["head"]))
            assert len(cells) == 1, (name, cells)
            seeds = {len(D.mean_runs(k)) for k in keys}
            assert len(seeds) == 1, (name, seeds)
            body.append(" & ".join([name, *cells.pop(), str(seeds.pop())]) + r" \\")
    header = [r"Model & Weights & \shortstack{State level read by\\prediction layer $\ell$} & "
              r"Prediction input & LM head & Seeds \\"]
    write(out, "tab_model_definitions", tabular("llclcc@{}", header, body, "3pt", fill=True))


def write_2x2(out: Path):
    """Validation loss by weight sharing x read (Two-tower: same-depth, Sequential: final),
    with each row's params and FLOPs: the separate-weight rows and the one-read controls,
    then the shared row and the references."""
    spec = MANIFEST["two_by_two"]

    def loss(k):
        return fmt_pm(D.nll_seeds(k), 3)

    def facts(*keys):
        """non-emb. / total params (M) and GFLOPs/token, 'a/b' when two arms differ"""
        cols = [[f"{D.arch_stats(k)['params_nonemb'] / 1e6:.1f}" for k in keys],
                [f"{D.arch_stats(k)['params_total'] / 1e6:.0f}" for k in keys],
                [f"{D.arch_stats(k)['flops_fwd_per_token'] / 1e9:.3f}" for k in keys]]
        return ["/".join(dict.fromkeys(c)) for c in cols]

    def contrast(weights, towers, tt, seq):
        ft, fs = config_facts(tt), config_facts(seq)
        # the row's placement follows from its config
        assert {ft["tying"], fs["tying"]} == ({"attn+MLP"} if weights == "Shared" else {"none"})
        assert ft["read"].startswith("layer-aligned") and fs["read"] == READ_TEXT["final"]
        d = statistics.fmean(D.nll_seeds(seq)) - statistics.fmean(D.nll_seeds(tt))
        delta = ("$+$" if d > 0 else "$-$") + f"{abs(d):.3f}"
        return " & ".join([weights, towers, loss(tt), loss(seq), delta, *facts(tt, seq)]) + r" \\"

    def one(k, cells):
        return (r"\multicolumn{2}{@{}l}{" + tex(paper_name(k)) + "} & "
                + " & ".join([*cells, "--", *facts(k)]) + r" \\")

    body = [contrast(*row) for row in spec["rows"]]
    tt_only, seq_only = spec["two_tower_only"], spec["sequential_only"]
    assert len(D.nll_seeds(tt_only)) == 1 and len(D.nll_seeds(seq_only)) == 1
    body += [one(tt_only, [loss(tt_only), "--"]), one(seq_only, ["--", loss(seq_only)])]
    # the <predict>-input variant drops the prediction table: it matches the Transformer's total
    assert facts(seq_only)[1] == facts(PS.BODY_TRANSFORMER)[1]
    body += [r"\midrule", contrast(*spec["shared"])]
    for k in spec["references"]:
        assert config_facts(k)["head"] == PS.BODY_HEAD, k
        body.append(r"\multicolumn{2}{@{}l}{" + PS.body_label(k) + r"} & \multicolumn{2}{c}{"
                    + loss(k) + "} & " + " & ".join(["--", *facts(k)]) + r" \\")
    header = [r" & & \multicolumn{2}{c}{Read} & $\Delta$ & \multicolumn{2}{c}{Params (M)} & "
              r"GFLOPs \\",
              r"\cmidrule(lr){3-4}\cmidrule(lr){6-7}",
              r"Weights & Towers & Two-tower & Sequential & Seq.$-$TT & non-emb. & total & "
              r"/token \\"]
    write(out, "tab_2x2", tabular("llcccccc@{}", header, body, "3pt", fill=True))


