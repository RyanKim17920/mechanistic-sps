PATCH_ARMS = (("prev1_answer_slot", "head"), ("ctrl_donor_prev1_answer_slot", "donor"))


def patching_recs() -> dict:
    """{arm: [{'head' | 'donor': (recovery fraction, 95% CI)} per seed]}: the answer-slot
    interchange patch of the state stream's strongest previous-token head, or a random donor"""
    recs = {}
    for k in analysis_arms():
        seeds = []
        for run, d in D.result_seeds("a9_patching", k):
            try:
                a = d["patching"]["natural"]["arms"]
                seeds.append({t: (float(a[arm]["recovery_fraction"]),
                                  [float(v) for v in a[arm]["recovery_ci95"]])
                              for arm, t in PATCH_ARMS})
            except (KeyError, TypeError):
                print(f"[patching] {run}: no answer-slot arms; skipped")
        if seeds:
            recs[k] = seeds
    return recs


def write_patching(out: Path):
    recs = patching_recs()

    def cell(k, t):
        # two seeds: seed 1 / seed 2 (each rounded once, matching the prose); one seed: the
        # value with its within-run 95% bootstrap interval in brackets
        vs = [s[t][0] for s in recs[k]]
        if len(vs) == 1:
            lo, hi = recs[k][0][t][1]
            return fmt(vs[0], 2) + r" {\scriptsize[" + fmt(lo, 2) + ", " + fmt(hi, 2) + "]}"
        return " / ".join(fmt(v, 2) for v in vs)

    def row(k):
        return [" & ".join([tex(paper_name(k)), cell(k, "head"), cell(k, "donor")]) + r" \\"]
    single_seed = [k for k in recs if len(recs[k]) < 2]
    cap = (r"Activation patching on validation text with a duplicated 256-token segment: "
           r"recovery from patching the strongest previous-token head at the answer slot, or "
           r"a random donor (control). Recovery is "
           r"$(\overline D_{\rm patched}-\overline D_{\rm corrupted})/(\overline D_{\rm clean}"
           r"-\overline D_{\rm corrupted})$, where $D$ is the answer-versus-distractor logit "
           r"difference. Two-seed rows give seed 1 / seed 2; one-seed rows give the value with "
           r"its within-run 95\% bootstrap interval in brackets.")
    write_float(out, "tab_patching", table_env(
        "tab:patching", cap, "lll", [r"Model & Head patched in & Random donor \\"],
        grouped_body(grouped(list(recs)), row), "4pt", pos="htbp"))


def _a13_grid(k, which):
    """{K: [delta per seed]} on the D.KS grid, dropping the native map and K beyond depth."""
    out = defaultdict(list)
    for _, d in D.a13_seeds(k):
        for K, y in zip(*D.a13_curve(d, which)):
            if K in D.KS:
                out[K].append(y)
    return out


def write_readdepth_full(out: Path):
    """Per-model read reach (a2: keep the N most recent state positions, far keys masked or
    mean-replaced) and read depth (a13: levels <= k / >= k)."""
    keys = [k for k in analysis_arms() if arch_group(k) != "transformer"]
    a2 = {k: {ab: D.a2_means(k, ab) for ab in ("mask", "mean")} for k in keys}
    a13 = {k: {w: _a13_grid(k, w) for w in ("caps", "floors")} for k in keys}
    # a13 sweeps whose read source was never trained as a read (a13_valid); captioned
    bad = [k for k in keys
           if any(not D.a13_valid(r, d) for r, d in D.result_seeds("a13_read_depth_cap", k))]
    keys = [k for k in keys if a2[k]["mask"] or a13[k]["caps"]]
    # a13 applies min/max(l, k) to the SAME-DEPTH (Two-tower) map l; for a model whose native
    # read is not same-depth (Sequential, 12+6) every bound also moves it off its native read
    starred = {k for k in keys if config_facts(k)["read"] != READ_TEXT["post"]}

    def v(x):
        return "--" if x is None else (f"{x:.3f}" if abs(x) < 0.1 else f"{x:.2f}")

    single_seed = set()

    def row_a(k):
        if 0 < max(len(a2[k]["mask"]), len(a2[k]["mean"])) < 2:
            single_seed.add(tex(paper_name(k)))
        cells = [fmt_pm_v([c[i] for c in a2[k][ab]], v) if a2[k][ab] else "--"
                 for ab in ("mask", "mean") for i in range(len(D.A2_CAPS))]
        return [" & ".join([tex(paper_name(k))] + cells) + r" \\"]

    def row_b(k, w):
        g = a13[k]
        if 0 < max([len(x) for w_ in g.values() for x in w_.values()] or [0]) < 2:
            single_seed.add(tex(paper_name(k)))
        cells = [fmt_pm_v(g[w][K], v) if g[w].get(K) else "--" for K in D.KS]
        if all(c == "--" for c in cells):    # no bound inside this model's state depth
            return []
        name = tex(paper_name(k)) + (r"$^{\ast}$" if k in starred else "")
        return [" & ".join([name] + cells) + r" \\"]

    ns = " & ".join(map(str, D.A2_CAPS))
    hdr_a = [r" & \multicolumn{4}{c}{masked, $N{=}$} & "
             r"\multicolumn{4}{c}{mean-replaced, $N{=}$} \\",
             r"\cmidrule(lr){2-5}\cmidrule(lr){6-9}",
             r"Model & " + ns + " & " + ns + r" \\"]

    def hdr_b(w):
        rel = r"\leq" if w == "caps" else r"\geq"
        return [r" & \multicolumn{6}{c}{levels $" + rel + r" k$, $k{=}$} \\",
                r"\cmidrule(lr){2-7}",
                r"Model & " + " & ".join(map(str, D.KS)) + r" \\"]
    spec_a, spec_b = "l" + "r" * 8, "l" + "r" * 6
    # the reach table's natural width is measured in box 0: too wide -> scaled down to
    # \linewidth; otherwise re-set as tabular* at \linewidth.  The read-depth grid is two
    # 6-column tables (levels <= k, levels >= k) that fit at \scriptsize.
    body_a = tabular(spec_a, hdr_a, grouped_body(grouped([k for k in keys if a2[k]["mask"]]),
                                                 row_a))[1:-1]
    tab_a = [r"\sbox0{%", r"\begin{tabular}{" + spec_a + "}", *body_a, r"\end{tabular}}%",
             r"\ifdim\wd0>\linewidth\resizebox{\linewidth}{!}{\usebox0}\else",
             r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}" + spec_a + "}", *body_a,
             r"\end{tabular*}\fi"]
    tab_b = []
    for w in ("caps", "floors"):
        tab_b += [r"\par\medskip"] + tabular(
            spec_b, hdr_b(w), grouped_body(grouped([k for k in keys if a13[k]["caps"]]),
                                           lambda k, w=w: row_b(k, w)), fill=True)
    cap = (r"Loss increase (nats/token; models as in "
           r"Tab.~\ref{tab:roster_full}) for every two-stream model "
           r"when prediction may read (top) only the $N$ most recent state positions, the "
           r"farther keys masked out or replaced by their mean, and (middle, bottom) only state "
           r"levels no deeper ($\leq K$) or no shallower ($\geq K$) than $K$, each prediction "
           r"layer's read level $\ell$ moved to $\min(\ell, K)$ or $\max(\ell, K)$ (--: $K$ "
           r"beyond the state depth, or the unchanged native read). $^{\ast}$Native read not "
           r"same-depth (Sequential: level $L_s$ from every layer; 12+6: level $\ell{+}6$): the "
           r"bounds are applied to the same-depth map $\ell$, so every bound, even $K{=}12$, "
           r"also moves every layer off its native read. The read-depth test does not "
           r"apply to SPS and AF-SPS (they read the keys each state layer computes)"
           + (r"; " + ", ".join(tex(paper_name(k)) for k in bad)
              + r" reuses the state tower's own keys and values, so its "
              r"bounds substitute untrained reads and are not shown" if bad else "") + ". "
           + pm_caption_note_rows(sorted(single_seed)))
    write_float(out, "tab_readdepth_full", "\n".join([
        AUTOGEN, r"\begin{table}[htbp]", r"\centering", r"\scriptsize",
        r"\caption{" + cap + "}", r"\label{tab:readdepth_full}", r"\setlength{\tabcolsep}{2pt}",
        *tab_a, *tab_b, r"\end{table}", ""]))


