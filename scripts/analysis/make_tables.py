@lru_cache(maxsize=None)
def wallclock_by_arm():
    g = defaultdict(list)
    with open(D.WALLCLOCK) as f:
        for line in f:
            if line.strip():
                r = json.loads(line)
                if r.get("tag") == WC["tag"]:
                    g[r["arm"]].append(r)
    return g


def _num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _median_metric(rs, section):
    vals = []
    for r in rs:
        sec = r.get(section)
        if isinstance(sec, dict):
            v = _num(sec.get("tokens_per_s"))
            if v is not None:
                vals.append(v)
    return (statistics.median(vals), len(vals)) if vals else (None, 0)


def _hosts(rs, section):
    return {r.get("host") for r in rs if isinstance(r.get(section), dict)
            and _num(r[section].get("tokens_per_s")) is not None}


def head_tying_speed_effect() -> float:
    """largest relative train-throughput difference between a tied and an untied head of the
    same model and kernel (justifies one tied-head Transformer reference for both groups)"""
    W, out = wallclock_by_arm(), 0.0
    for t, u in WC["head_pairs"]:
        a, b = _median_metric(W.get(t, []), "train")[0], _median_metric(W.get(u, []), "train")[0]
        if a and b:
            out = max(out, abs(a - b) / a)
    return out


def train_rel_same_kernel() -> dict:
    """key -> train throughput relative to the same-kernel tied-head Transformer: the
    two-tower arms run on torch flex-attention (divided by the Transformer on flex), the
    Transformer and SPS on the repo's Triton kernels (divided by the Triton Transformer)."""
    W = wallclock_by_arm()
    ref = {t: _median_metric(W.get(t, []), "train")[0] for t in (BASE_TAG, FLEX_TAG)}
    exp_to_tag = {e: t for t, e in WC["arms"].items() if not t.endswith("_flex")}
    out = {}
    for key in ARMS:
        tag = exp_to_tag.get(key)
        v = _median_metric(W.get(tag, []), "train")[0] if tag else None
        rtag = FLEX_TAG if config_facts(key)["family"] == "two_tower" else BASE_TAG
        if v is not None and ref[rtag] is not None:
            out[key] = v / ref[rtag]
    return out


