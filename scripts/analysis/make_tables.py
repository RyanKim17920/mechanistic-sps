#!/usr/bin/env python3
r"""The paper's tables (booktabs), fully data-driven.  Every number is read through
paper_data.py (ledger, result JSONs, wallclock benchmark, arch_stats.json), every
architecture fact from the instantiated Hydra config, every row list from
paper_manifest.yaml; the data checks behind the text's claims are assertions.

Two kinds of output:
  * a whole table float (caption, label, tabular), which main.tex inputs through
    \inputwithcaption{<file>}{<caption>}: main.tex supplies the caption it prints
     <outdir>/tab_circuit.tex            copying circuit, body models (seed means, Holm codes)
     <outdir>/tab_roster_full.tex        every 20B run: config facts, params, FLOPs, speed, NLL
     <outdir>/tab_circuit_full.tex       copying circuit, every run
     <outdir>/tab_patching.tex           activation patching recovery
     <outdir>/tab_readdepth_full.tex     read reach and read depth, every two-stream model
     <outdir>/tab_probe_floors.tex       last-layer probes, trained vs untrained
     <outdir>/tab_lesion_mean.tex        zero vs mean ablation
     <outdir>/tab_efficiency.tex         throughput, KV cache, FLOPs
  * a tabular only, whose float, caption and label are in main.tex
     <outdir>/tab_model_definitions.tex  weight sharing, read level, input, head, seeds
     <outdir>/tab_2x2.tex                weight sharing x read, plus single-read rows
     <outdir>/tab_token_gain.tex         token and gain shares, repeat-distance and induction
     <outdir>/tab_control_counts.tex     distinct pattern-matched control triples
     <outdir>/tab_finalread.tex          Sequential minus Two-tower loss by repeat distance
  and <outdir>/numbers.tex, the numbers stated in the text (paper_numbers.py).

Read level (paper convention): state level l = output of state layer l (level 0 =
embeddings).  Prediction layer l reads level
    l-1  read_map "pre"  (SPS, AF-SPS: the k/v that state layer l computes from its input)
    l    read_map "post" (Two-tower)
    l+k  read_map "top"  (Two-tower 12+6: k = L_s - L_p)
    final read_map "final" (Sequential: level L_s at every prediction layer)

Usage:  python scripts/analysis/make_tables.py [--outdir paper/tables]
"""
