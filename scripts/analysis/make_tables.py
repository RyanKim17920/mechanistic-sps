@lru_cache(maxsize=None)
def config_facts(key: str) -> dict:
    """Shared weights / read level / LM head / prediction-stream input of an arm, read from
    its instantiated model config (paper_data.arch_stats), and cross-checked against the
    manifest's fields (disagreements are printed and collected in MISMATCHES)."""
    st = D.arch_stats(key)
    fam = st["family"]
    head = "tied" if st["tie_lm_head"] else "untied"
    if fam == "standard":
        f = dict(family=fam, tying="--", shared="--", read="--", read_disp="--", head=head,
                 pred_input="--")
    elif fam == "sps":
        # SPS: one stack serves both slots; the prediction slot at layer l reads the k/v the
        # state slots compute at layer l from their input, i.e. level l-1.
        f = dict(family=fam, tying="one stack", shared="one stack", read=READ_TEXT["pre"],
                 read_disp=r"$\ell{-}1$", head=head,
                 pred_input=PRED_INPUT_TEXT[st["predict_embedding"]])
    else:
        attn, ffn_tied = st["tie_attn_across_towers"], st["tie_ffn_across_towers"]
        ffn_pooled, norms = st["share_ffn_across_towers"], st["tie_norms_across_towers"]
        parts = [n for n, on in (("attn", attn), ("MLP", ffn_tied or ffn_pooled)) if on]
        shared = [n for n, on in (("attn.", attn), ("MLP", ffn_tied), ("pooled MLP", ffn_pooled),
                                  ("norms", norms)) if on]
        rm = st["read_map"]
        read_disp = {"pre": r"$\ell{-}1$", "post": r"$\ell$", "final": "final",
                     "top": rf"$\ell{{+}}{st['state_n_layer'] - st['pred_n_layer']}$"}[rm]
        f = dict(family=fam, tying="+".join(parts) or "none",
                 shared=", ".join(shared) or "none", read=READ_TEXT[rm], read_disp=read_disp,
                 head=head, pred_input=PRED_INPUT_TEXT[st["predict_embedding"]])
    a = ARMS[key]
    expect = {"tying": {"single stream": "--"}.get(a["tying"], a["tying"]), "read": a["read"],
              "head": a["head"], "pred_input": a["pred_input"] or "--"}
    for fld, want in expect.items():
        if want != f[fld]:
            msg = f"{key}: config gives {fld}={f[fld]!r}, the manifest says {want!r}"
            MISMATCHES.append(msg)
            print(f"[MISMATCH] {msg}")
    return f


# architecture groups of the per-model appendix tables, assigned from the config
GROUPS = ["transformer", "sps", "layer", "final", "shared"]


def arch_group(key: str) -> str:
    f = config_facts(key)
    if f["family"] == "standard":
        return "transformer"
    if f["family"] == "sps" or "pooled MLP" in f["shared"]:
        return "sps"                     # SPS and AF-SPS (one pooled MLP per position)
    if f["tying"] == "attn+MLP":
        return "shared"                  # every layer weight shared across the towers
    return "final" if f["read"] == READ_TEXT["final"] else "layer"


def paper_name(key: str) -> str:
    """The one row name every appendix table uses for an arm (manifest `name`, else its
    label)."""
    return ARMS[key].get("name") or ARMS[key]["label"]


def roster_name(key: str) -> str:
    """paper_name without its head / input qualifier, for a table whose Variant column
    states head and input on every row (tab:roster_full)"""
    n = paper_name(key).replace(", tied head", "")
    if " (" in n and ("head" in n or PREDTOK in n):
        n = n.split(" (")[0]
    return n


PRED_INPUT_SHORT = {"table": "own table", "pause": PREDTOK}


def variant(key: str, qualifiers: bool = True) -> str:
    """What distinguishes an arm from its same-name siblings, from the config: a partial
    weight share or a non-default read, then "LM head / prediction-stream input".
    qualifiers=False: head / input only."""
    f = config_facts(key)
    parts = []
    if qualifiers and f["family"] == "two_tower" and f["tying"] not in ("none", "attn+MLP") \
            and arch_group(key) != "sps":
        parts.append("shared " + f["shared"].replace(", norms", ""))
    if qualifiers and f["read"] == READ_TEXT["top"]:
        parts.append("top-aligned")
    hi = f["head"]
    if f["pred_input"] != "--":
        hi += " / " + PRED_INPUT_SHORT[f["pred_input"]]
    return "; ".join(parts + [hi])


def grouped(keys):
    """[[keys] per architecture group] in GROUPS order; within a group by size
    (non-embedding params), then name (depth split), then variant."""
    by = defaultdict(list)
    for k in keys:
        by[arch_group(k)].append(k)
    return [sorted(by[g], key=lambda k: (round(D.arch_stats(k)["params_nonemb"] / 1e6),
                                         paper_name(k), variant(k)))
            for g in GROUPS if by.get(g)]


def grouped_body(groups, row_fn):
    """booktabs body: groups separated by \\midrule (every row name says its family)."""
    body = []
    for i, items in enumerate(groups):
        if i:
            body.append(r"\midrule")
        for it in items:
            body.extend(row_fn(it))
    return body


def analysis_arms():
    """the arms of the per-model analysis tables (not the roster-only controls)"""
    return [k for k, a in ARMS.items() if not a.get("roster_only")]


