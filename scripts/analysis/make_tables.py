def prev_mass(a5, q, k=None):
    """max over heads of query stream q (optionally only key population k) of the
    natural-text previous-token attention mass."""
    rows = [r for r in a5["natural"]["per_head"] if r["query_stream"] == q
            and (k is None or r["key_stream"] == k) and "prev_token_mass" in r]
    return max(max(r["prev_token_mass"]) for r in rows)


def check_prev_mass(a5):
    for q in a5["query_streams"]:
        prof = max(v["max_prev_token_mass"] for v in a5["prev_token_profile"].values()
                   if v["stream"] == q)
        assert abs(prof - round(prev_mass(a5, q), 5)) < 1e-5, (a5["run"], q, prof)


def _has_l1(draw):
    return any(h["block"] == 0 for h in draw["heads"])    # layer 1 = block 0


@lru_cache(maxsize=None)
def ctrl_files(run) -> dict:
    """{mode: a9 control JSON} for the 100-draw control files of `run` that exist"""
    out = {}
    for mode, suffix in CTRL_FILES:
        d = D.result("a9_patching", f"{run}_{suffix}")
        if d is not None:
            out[mode] = d
    return out


def ctrl_p(run):
    """{mode: dict(k, n, p, k_l1, drivers, draws)} from the 100-draw control files, every
    mode on ONE metric: accuracy lost on induction tokens the clean model predicts correctly.
    p+1 is recomputed from the draws and asserted equal to the stored one; k_l1 = exceeding
    draws that contain a layer-1 head; drivers = heads (layer, head), both 1-indexed, present
    in every exceeding draw."""
    out = {}
    for mode, d in ctrl_files(run).items():
        assert d["ctrl_mode"] == CTRL_MODE[mode], (run, d["ctrl_mode"], mode)
        excl = d.get("ctrl_exclude_layers") or []
        assert (excl == [1]) == mode.endswith("exL1"), (run, mode, excl)
        h = d["ctrl_summary"]["headline"]
        assert h["metric"] == "accuracy lost on " + P_METRIC, (run, h["metric"])
        draws = [x for x in d["ctrl_draws"] if x["sets"].get(P_METRIC, {}).get("n")]
        if excl:
            assert not any(_has_l1(x) for x in draws), (run, mode)
        costs = [-x["sets"][P_METRIC]["d_acc_control"] for x in draws]
        prev = float(h["prev_cost"])
        for src in (d, D.result("a9_patching", run)):
            assert abs(prev + src["natural"][P_METRIC]["d_acc"]) < 1e-9, run
        assert len(costs) == h["n_draws"] == d["n_ctrl_draws"] == 100, run
        ge = [c >= prev - 1e-9 for c in costs]
        k = sum(ge)
        ex = [x for g, x in zip(ge, draws) if g]
        drivers = set.intersection(*[{(hd["block"] + 1, hd["head"] + 1) for hd in x["heads"]}
                                     for x in ex]) if ex else set()
        p = (k + 1) / (len(costs) + 1)
        assert abs(p - h["p_plus1"]) < 1e-9, (run, mode, p, h["p_plus1"])
        out[mode] = dict(k=k, n=len(costs), p=p, drivers=drivers,
                         k_l1=sum(g and _has_l1(x) for g, x in zip(ge, draws)),
                         draws=[frozenset((hd["block"], hd["head"]) for hd in x["heads"])
                                for x in draws])
    return out


def circuit_rows(entries):
    """entries: [(key, label, runs)] -> one row per run with an a5 JSON: previous-token
    mass / mean lift / heads with lift > 3 per query stream (split by key population where
    a model has two), the a9 induction-token ablation vs. its same-layer control, and the
    100-draw p+1 values where the control files exist."""
    rows = []
    for key, label, runs in entries:
        seeds = D.result_seeds("a5_induction", key, runs=runs)
        if not seeds:
            print(f"[circuit] no a5 for {key}; skipped")
            continue
        for run, a5 in seeds:
            check_prev_mass(a5)
            nat = (D.result("a9_patching", run) or {}).get("natural", {})
            ind, allt = nat.get("induction"), nat.get("all")
            abl = None if not ind else (ind["d_nll"], ind.get("d_nll_control"))
            allc = None if not allt else (allt["d_nll"], allt.get("d_nll_control"))
            agg = a5["natural"]["aggregate_2x2"]
            qs = list(a5["query_streams"])            # ["single"] or ["state", "pred"]
            key_pops = a5["key_streams"]
            sub = []
            for kp in key_pops:
                cs = [agg[f"{q}_query__{kp}_key"] for q in qs]
                nhs = [c["n_heads"] for c in cs]   # per query stream (asym 12+6: 144 / 72)
                nh = nhs[0] if len(set(nhs)) == 1 else "/".join(map(str, nhs))
                pm = [prev_mass(a5, q, kp if len(key_pops) > 1 else None) for q in qs]
                pad = [None] * (2 - len(qs))           # single stream: no P column
                sub.append(dict(kp=kp, pm=pm + pad, lift=[c["mean_lift"] for c in cs] + pad,
                                gt3=[c["n_heads_lift_gt3"] for c in cs] + pad, nh=nh))
            rows.append(dict(key=key, run=run, label=label,
                             seed=ARMS[key]["seeds"].index(run) + 1,
                             nseeds=len(seeds), sub=sub, abl=abl, allc=allc, ps=ctrl_p(run)))
    return rows


def _pair(a, b, nd=3):
    return "/".join("--" if v is None else fmt(v, nd) for v in (a, b))


def _kp_name(name, kp, first):
    kp = {"state": "state keys", "pred": "pred.\\ keys"}[kp]
    return f"{name}, {kp}" if first else r"\quad " + kp


def _multirow_tail(cells, tail, i, n):
    """SPS rows split by key population share their tail cells (\\multirow)."""
    if n > 1:
        return cells + ([rf"\multirow{{{n}}}{{*}}{{{c}}}" for c in tail] if i == 0
                        else [""] * len(tail))
    return cells + tail


def circuit_body(rows):
    """tab:circuit-full: one row per run (and key population)."""
    body = []
    prev_key = None
    for r in rows:
        if prev_key is not None and r["key"] != prev_key:
            body.append(r"\addlinespace")
        prev_key = r["key"]
        abl = "--" if r["abl"] is None else _pair(*r["abl"])
        allc = "--" if r["allc"] is None else _pair(*r["allc"])
        ps = ["/".join(f"{r['ps'][m]['p']:.3f}" if m in r["ps"] else "--" for m in pair)
              if any(m in r["ps"] for m in pair) else "--" for pair in P_PAIRS]
        name = tex(r["label"]) + (f" (s{r['seed']})" if r["nseeds"] > 1 else "")
        for i, s in enumerate(r["sub"]):
            heads = "/".join("--" if v is None else str(v) for v in s["gt3"])
            cells = [_kp_name(name, s["kp"], i == 0) if len(r["sub"]) > 1 else name,
                     _pair(*s["pm"], nd=2), _pair(*s["lift"], nd=2), heads]
            body.append(" & ".join(_multirow_tail(cells, [abl, allc] + ps, i, len(r["sub"])))
                        + r" \\")
    return body


def _holm_sig(ps, alpha=ALPHA):
    """Holm-Bonferroni step-down over one seed's family of tests (ps: {mode: {p, ...}}).
    Returns {mode: bool}: whether that test's p survives, comparing the i-th smallest p to
    alpha/(n-i)."""
    items = sorted(ps.items(), key=lambda kv: kv[1]["p"])
    sig, chain_ok = {}, True
    for i, (mode, v) in enumerate(items):
        chain_ok = chain_ok and v["p"] <= alpha / (len(items) - i)
        sig[mode] = chain_ok
    return sig


def holm_code(run, pool):
    """One seed's Holm verdict for one control pool (Holm within the (model, seed) family
    of its 4 controls): 'all' if the ablation is Holm-significant against that pool both
    with control heads from all layers and with layer 1 excluded; 'excl.' if only with
    layer 1 excluded; '--' if neither.  (Significant over all layers but not after
    excluding layer 1 does not occur; asserted.)"""
    sig = {m for m, ok in _holm_sig(run["ps"]).items() if ok}
    a, e = pool in sig, pool + "_exL1" in sig
    assert not (a and not e), (run["run"], pool, run["ps"])
    return "all" if a else ("excl." if e else "--")


def holm_cells(runs):
    """(random cell, pattern-matched cell), each 'seed1/seed2' of holm_code."""
    return tuple("/".join(holm_code(r, pool) for r in runs) for pool in HOLM_POOLS)


def circuit_body_by_model(rows):
    """tab:circuit: one row per model (SPS split into its state-keys / pred.-keys sub-rows),
    seed means for prev.-mass, lift and the two DeltaNLL columns, and the Holm codes."""
    groups = {}
    for r in rows:
        groups.setdefault(r["key"], []).append(r)
    body = []
    for gi, runs in enumerate(groups.values()):
        n_sub = len(runs[0]["sub"])
        if gi and n_sub > 1:      # set the two key-population sub-rows apart
            body.append(r"\addlinespace")
        hr, hp = holm_cells(runs)

        def col(field, j, i=None):
            return mean_only([(r["sub"][i][field][j] if i is not None else
                               (r[field][j] if r[field] else None)) for r in runs],
                             2 if i is not None else 3)
        for i in range(n_sub):
            name = tex(runs[0]["label"])
            if n_sub > 1:
                name = _kp_name(name, runs[0]["sub"][i]["kp"], i == 0)
            cells = [name, f"{col('pm', 0, i)}/{col('pm', 1, i)}",
                     f"{col('lift', 0, i)}/{col('lift', 1, i)}"]
            tail = [f"{col('abl', 0)}/{col('abl', 1)}", f"{col('allc', 0)}/{col('allc', 1)}",
                    hr if i == 0 else "", hp if i == 0 else ""]
            body.append(" & ".join(_multirow_tail(cells, tail, i, n_sub)) + r" \\")
    return body


def _ctrl_files_complete(run):
    """True iff the four 100-draw a9 control files of `run` exist and parse with 100 draws;
    a seed whose control files are still being written is left out of tab:circuit."""
    try:
        return set(ctrl_p(run)) == {m for m, _ in CTRL_FILES}
    except (AssertionError, KeyError, ValueError):   # json.JSONDecodeError is a ValueError
        return False


def circuit_runs(k):
    """seed rule for tab:circuit: runs with an a5 JSON, its a9 companion and all four
    complete a9 control files"""
    return D.pick_seeds(k, lambda r: D.result("a5_induction", r) is not None
                        and D.result("a9_patching", r) is not None
                        and _ctrl_files_complete(r))


