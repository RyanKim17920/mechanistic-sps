# SPS's learned prediction token (Monea et al.'s <predict>; config predict_embedding:
# constant): every prediction position gets this one learned input instead of its token's
# embedding.  The tables (and the manifest labels) print it with this exact LaTeX.
PREDTOK = r"$\langle$predict$\rangle$"


def tex(s: str) -> str:
    """escape TeX specials, leaving the PREDTOK LaTeX intact"""
    return PREDTOK.join(_tex1(part) for part in s.split(PREDTOK))


def _tex1(s: str) -> str:
    return (s.replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
            .replace("_", r"\_").replace("#", r"\#"))


def fmt(v, nd=3):
    """signed number; a value that rounds to zero prints as 0.000 (never -0.000)"""
    if abs(v) < 0.5 * 10 ** -nd:
        v = 0.0
    s = f"{v:.{nd}f}"
    return s.replace("-", "$-$")


# SEED RULE for every cell: one value prints plain; two print as the seed mean with half
# their range as a subscript (2.801$_{\pm.002}$).
def _pm_part(half, nd):
    """the +- part alone, e.g. '.002' (no leading 0).  A half-range that rounds to zero at
    the shown precision prints as '<.001' (a rounded zero is not zero seed variation)."""
    txt = f"{half:.{nd}f}"
    if float(txt) == 0:
        return "<." + "0" * (nd - 1) + "1" if nd > 0 else "<1"
    return txt.lstrip("0") if half < 1 else txt


def fmt_pm(vals, nd=3):
    vals = [v for v in vals if v is not None]
    if not vals:
        return "--"
    m = statistics.fmean(vals)
    if len(vals) < 2:
        return fmt(m, nd)
    half = abs(max(vals) - min(vals)) / 2
    return fmt(m, nd) + r"$_{\pm" + _pm_part(half, nd) + "}$"


def mean_only(vals, nd=3):
    """the plain seed mean (tab:circuit; the seed ranges are in tab:circuit-full)"""
    vals = [v for v in vals if v is not None]
    if not vals:
        return "--"
    return fmt(statistics.fmean(vals), nd)


def fmt_pm_v(vals, vfmt):
    """fmt_pm with a caller-supplied scalar formatter; the +- part takes the mean's decimal
    places."""
    vals = [x for x in vals if x is not None]
    if not vals:
        return "--"
    m = statistics.fmean(vals)
    if len(vals) < 2:
        return vfmt(m)
    half = abs(max(vals) - min(vals)) / 2
    txt = vfmt(m)
    nd = len(txt.rsplit(".", 1)[1]) if "." in txt else 0
    return txt + r"$_{\pm" + _pm_part(half, nd) + "}$"


def pm_caption_note(single_seed_labels) -> str:
    """The one caption sentence every table with a $\\pm$ cell states once."""
    base = r"$\pm$ is half the range over two seeds"
    if not single_seed_labels:
        return base + "."
    verb = " has" if len(single_seed_labels) == 1 else " have"
    return base + "; " + ", ".join(single_seed_labels) + verb + " one seed."


def pm_caption_note_rows(single_seed_labels) -> str:
    """pm_caption_note for a table whose model names can label both a one-seed and a
    two-seed variant: say that rows without $\\pm$ are single-seed."""
    base = r"$\pm$ is half the range over two seeds"
    return base + (r"; rows without $\pm$ have one seed." if single_seed_labels else ".")


def tabular(spec, header, body, colsep=None, fill=False):
    """A booktabs tabular (optionally after its \\tabcolsep), as a list of lines.  fill: set
    at \\linewidth as tabular* with \\extracolsep{\\fill}, so a table narrower than the text
    spreads its columns across the full width."""
    begin, end = ((r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}" + spec + "}",
                   r"\end{tabular*}") if fill else
                  (r"\begin{tabular}{" + spec + "}", r"\end{tabular}"))
    return ([r"\setlength{\tabcolsep}{" + colsep + "}"] if colsep else []) + [
        begin, r"\toprule", *header, r"\midrule", *body, r"\bottomrule", end]


def write(out: Path, stem: str, lines):
    """<out>/<stem>.tex, a tabular main.tex wraps in its own float; the last line ends in %
    so the file adds no space where it is input"""
    p = out / f"{stem}.tex"
    p.write_text("\n".join([AUTOGEN, *lines]) + "%\n")
    print(f"WROTE {p}")


def table_env(label, cap, spec, header, body, colsep, size=r"\footnotesize", pos="t"):
    """A whole table float (tabular* at \\linewidth, see `tabular`) with its own caption;
    main.tex's \\inputwithcaption replaces that caption with the one it prints."""
    return "\n".join([AUTOGEN, r"\begin{table}[" + pos + "]", r"\centering", size,
                      r"\caption{" + cap + "}", r"\label{" + label + "}",
                      *tabular(spec, header, body, colsep, fill=True), r"\end{table}", ""])


def write_float(out: Path, stem: str, text: str):
    p = out / f"{stem}.tex"
    p.write_text(text)
    print(f"WROTE {p}")


