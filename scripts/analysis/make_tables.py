BUCKETS = [("never", "never"), ("1-16", "1--16 back"), ("17-64", "17--64"),
           ("65-256", "65--256"), ("257-1024", "257--1024"), ("1025+", "$>$1024")]


def read_contrasts():
    """{'12+12' | '6+6': (Two-tower arm, Sequential arm)}: the separate-weight rows of tab:2x2"""
    return {towers: (tt, seq) for w, towers, tt, seq in MANIFEST["two_by_two"]["rows"]}


def repeat_distance():
    """g3_final_read_mechanism's A3 buckets per depth, checked against the seed rule"""
    g3 = json.loads((D.RESULTS / "g3_final_read_mechanism.json").read_text())
    out = {}
    for towers, (tt, seq) in read_contrasts().items():
        assert config_facts(tt)["tying"] == config_facts(seq)["tying"] == "none"
        a3 = g3["pairs"][towers]["a3"]
        assert a3["runs"]["tt"] == D.mean_runs(tt) and a3["runs"]["seq"] == D.mean_runs(seq)
        out[towers] = a3
    return out


def induction_sweep():
    """{towers: [(induction-token share, share of Sequential's gain) per same-seed pair]} on
    a9's natural-text sweep: gain share = (n_ind / n_all) (Delta_ind / Delta_all), Delta =
    Two-tower minus Sequential mean NLL."""
    out = {}
    for towers, (tt, seq) in read_contrasts().items():
        out[towers] = []
        for rt, rs in zip(D.mean_runs(tt), D.mean_runs(seq)):
            a, b = D.result("a9_patching", rt)["natural"], D.result("a9_patching", rs)["natural"]
            assert a["all"]["n"] == b["all"]["n"] and a["induction"]["n"] == b["induction"]["n"]
            share = a["induction"]["n"] / a["all"]["n"]
            gain = ((a["induction"]["clean_nll"] - b["induction"]["clean_nll"])
                    / (a["all"]["clean_nll"] - b["all"]["clean_nll"]))
            out[towers].append((share, share * gain))
    return out


def pct_range(vals, nd=0):
    lo, hi = (f"{100 * v:.{nd}f}" for v in (min(vals), max(vals)))
    return lo if lo == hi else f"{lo}--{hi}"


def write_finalread(out: Path):
    rd = repeat_distance()
    order = ("12+12", "6+6")
    shares = {rd[t]["buckets"][b]["share"] for t in order for b, _ in BUCKETS}
    assert len(shares) == len(BUCKETS)          # both depths score the same tokens
    body = []
    for b, name in BUCKETS:
        cells = [name, f"{100 * rd[order[0]]['buckets'][b]['share']:.1f}\\%"]
        for t in order:
            x = rd[t]["buckets"][b]
            cells += [f"${x['diff_seq_minus_tt']:.3f}$", f"${x['rel_diff_pct']:.1f}$\\%",
                      f"{100 * x['share_of_gain']:.0f}\\%"]
        body.append(" & ".join(cells) + r" \\")
    body += [r"\midrule", "all & 100\\% & " + " & & & ".join(
        f"${rd[t]['overall_diff_seq_minus_tt']:.3f}$" for t in order) + r" & & \\"]
    header = [r" & & \multicolumn{3}{c}{12+12} & \multicolumn{3}{c}{6+6} \\",
              r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
              r"Last occurrence & tokens & $\Delta$ & rel. & gain & $\Delta$ & rel. & gain \\"]
    write(out, "tab_finalread", tabular("lrrrrrrr", header, body, "4pt", fill=True))


def write_token_gain(out: Path):
    rd, ind = repeat_distance(), induction_sweep()
    never = [rd[t]["buckets"]["never"] for t in rd]
    ind_share = {round(s, 12) for pairs in ind.values() for s, _ in pairs}
    assert len({x["share"] for x in never}) == 1 and len(ind_share) == 1
    body = [f"Never-seen (R) & {100 * never[0]['share']:.1f}\\% & "
            f"{pct_range([x['share_of_gain'] for x in never])}\\% \\\\",
            f"Induction tokens (I) & {100 * ind_share.pop():.1f}\\% & "
            f"{pct_range([g for pairs in ind.values() for _, g in pairs])}\\% \\\\"]
    header = [r"Token group & Share of tokens & Share of Sequential's gain \\"]
    write(out, "tab_token_gain", tabular("lcc@{}", header, body, "6pt", fill=True))


